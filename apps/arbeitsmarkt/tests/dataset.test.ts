import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  DEFAULT_SEED,
  generateDataset,
  loadCommittedDataset,
  serializeDataset,
  syntheticOnly,
  SYNTHETIC_STATEMENT,
} from "@/lib/dataset";

const APP_ROOT = join(__dirname, "..");

describe("synthetic dataset generator", () => {
  it("is deterministic: same seed produces byte-identical serialization", () => {
    const a = serializeDataset(generateDataset(DEFAULT_SEED));
    const b = serializeDataset(generateDataset(DEFAULT_SEED));

    // Paste-friendly comparison for acceptance evidence (A-2).
    console.log("determinism byte lengths:", a.length, b.length);
    console.log("determinism equal:", a === b);
    console.log("determinism first 120 chars of a:\n", a.slice(0, 120));

    expect(a).toBe(b);
    expect(a.length).toBeGreaterThan(100);
  });

  it("committed data/listings.json equals a fresh generation from the default seed", () => {
    const committedRaw = readFileSync(join(APP_ROOT, "data", "listings.json"), "utf8");
    const generatedRaw = serializeDataset(generateDataset(DEFAULT_SEED));

    console.log("committed bytes:", committedRaw.length);
    console.log("generated bytes:", generatedRaw.length);
    console.log("committed === generated:", committedRaw === generatedRaw);

    expect(committedRaw).toBe(generatedRaw);
    expect(loadCommittedDataset().meta.seed).toBe(DEFAULT_SEED);
    expect(loadCommittedDataset().meta.recordCount).toBe(24);
    expect(loadCommittedDataset().records).toHaveLength(24);
  });

  it("flags every record synthetic in the dataset, and the synthetic-only filter returns all", () => {
    const dataset = generateDataset(DEFAULT_SEED);

    expect(dataset.meta.synthetic).toBe(true);
    expect(dataset.meta.statement).toBe(SYNTHETIC_STATEMENT);

    for (const record of dataset.records) {
      expect(record.synthetic).toBe(true);
      expect(record.companyName.startsWith("SYN-")).toBe(true);
    }

    const filtered = syntheticOnly(dataset.records);
    console.log("record count:", dataset.records.length);
    console.log("synthetic-only filter count:", filtered.length);
    console.log(
      "sample record shape:",
      JSON.stringify(
        {
          id: dataset.records[0]?.id,
          synthetic: dataset.records[0]?.synthetic,
          companyName: dataset.records[0]?.companyName,
          companyParts: dataset.records[0]?.companyParts,
        },
        null,
        2,
      ),
    );

    expect(filtered).toHaveLength(dataset.records.length);
    expect(filtered).toEqual(dataset.records);
  });

  it("does not use Math.random in the generator modules", () => {
    const files = ["generate.ts", "rng.ts", "parts.ts", "index.ts"].map((name) =>
      readFileSync(join(APP_ROOT, "lib", "dataset", name), "utf8"),
    );
    for (const source of files) {
      expect(source).not.toMatch(/\bMath\.random\b/);
    }
  });

  it("does not consult the clock or the environment in the generator", () => {
    // Every generator module, not only generate.ts: a draw or a clock read added in `parts.ts`
    // breaks determinism just as thoroughly, and the earlier version of this test only read one
    // file.
    const files = ["generate.ts", "rng.ts", "parts.ts", "index.ts"].map((name) =>
      readFileSync(join(APP_ROOT, "lib", "dataset", name), "utf8"),
    );

    // `new Date()` is the gap that mattered. Matching only `Date.now` let a generator that shifts
    // its whole output window by the current minute pass this assertion untouched — the break was
    // applied and the suite stayed green. It is caught by the committed-equality test below, which
    // is why this is a weak guard rather than a hole, but a guard that reads as "the clock is not
    // consulted" has to mean it.
    const forbidden: Array<[string, RegExp]> = [
      ["Date.now", /\bDate\.now\b/],
      // `new Date()` with no argument reads the clock; `new Date(ms)` from a fixed value does not,
      // and is how the generator turns its seeded offset into a date. Requiring the empty argument
      // list is what separates the hazard from the legitimate use — checked after the first version
      // flagged `new Date(ms)` and failed on a working generator.
      ["new Date()", /\bnew\s+Date\s*\(\s*\)/],
      ["performance.now", /\bperformance\.now\b/],
      ["process.env", /\bprocess\.env\b/],
      ["Math.random", /\bMath\.random\b/],
    ];

    for (const [label, pattern] of forbidden) {
      for (const source of files) {
        expect(source, `${label} must not appear in the generator`).not.toMatch(pattern);
      }
    }
  });
});

describe("no network acquisition path", () => {
  function collectSources(dir: string): string[] {
    const out: string[] = [];
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        out.push(...collectSources(full));
      } else if (/\.(ts|tsx|js|mjs)$/.test(entry.name)) {
        out.push(full);
      }
    }
    return out;
  }

  it("lib/ and app/ contain no fetch() to an external host", () => {
    const files = [
      ...collectSources(join(APP_ROOT, "lib")),
      ...collectSources(join(APP_ROOT, "app")),
    ];
    const offenders: string[] = [];

    for (const file of files) {
      const src = readFileSync(file, "utf8");
      if (/\bfetch\s*\(/.test(src)) {
        offenders.push(file.replace(APP_ROOT + "/", ""));
      }
      if (/https?:\/\//.test(src) && /\bfetch\s*\(/.test(src)) {
        offenders.push(file.replace(APP_ROOT + "/", ""));
      }
    }

    expect(offenders).toEqual([]);
  });
});
